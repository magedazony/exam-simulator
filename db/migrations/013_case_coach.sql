-- ---------------------------------------------------------------- case set query

-- Returns full case study with its published questions (ordered by case_ordinal)
CREATE OR REPLACE FUNCTION case_set_json(p_case uuid, p_user uuid DEFAULT NULL)
RETURNS jsonb LANGUAGE sql STABLE AS $$
  SELECT jsonb_build_object(
    'id', cs.id,
    'publicCode', cs.public_code,
    'title', cs.title,
    'titleAr', cs.title_ar,
    'scenario', cs.scenario,
    'scenarioAr', cs.scenario_ar,
    'language', cs.language,
    'questions', coalesce((
      SELECT jsonb_agg(
        engine_question(qv.id, 'live') || jsonb_build_object('ordinal', qv.case_ordinal)
        ORDER BY qv.case_ordinal
      )
      FROM question_versions qv
      WHERE qv.case_study_id = cs.id AND qv.workflow_state = 'published'
    ), '[]'::jsonb)
  )
  FROM case_studies cs WHERE cs.id = p_case AND cs.status = 'published';
$$;

-- ---------------------------------------------------------------- AI coach hints

-- Records a hint request (audit trail; hints themselves are generated by the API layer)
CREATE TABLE coach_hint_requests (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id     uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  question_id uuid NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  hint_type   text NOT NULL DEFAULT 'general' CHECK (hint_type IN ('general', 'approach', 'eliminate', 'explain')),
  tokens_used integer,
  requested_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX coach_hints_user_idx ON coach_hint_requests (user_id, requested_at DESC);

-- Daily hint quota check (free: 3/day, pass: unlimited)
CREATE OR REPLACE FUNCTION hints_today(p_user uuid, p_now timestamptz) RETURNS integer LANGUAGE sql STABLE AS $$
  SELECT count(*)::integer FROM coach_hint_requests
  WHERE user_id = p_user AND requested_at >= date_trunc('day', p_now);
$$;

-- ---------------------------------------------------------------- subscription helpers

-- Restore a purchase by transaction ID (iOS/Android)
-- Uses the existing entitlements table (source='store', external_ref=transaction_id)
CREATE OR REPLACE FUNCTION restore_purchase(p_user uuid, p_transaction_id text, p_product_id text, p_now timestamptz)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE
  v_plan_code text;
  v_days      integer;
  v_ends_at   timestamptz;
BEGIN
  -- Check if already redeemed via entitlements
  SELECT ends_at INTO v_ends_at
  FROM entitlements
  WHERE user_id = p_user AND source = 'store' AND external_ref = p_transaction_id;
  IF FOUND THEN
    RETURN jsonb_build_object('status', 'already_redeemed', 'endsAt', v_ends_at);
  END IF;
  -- Look up plan from product
  SELECT plan_code INTO v_plan_code
  FROM plan_prices WHERE store_product_id = p_product_id LIMIT 1;
  IF v_plan_code IS NULL THEN
    RETURN jsonb_build_object('status', 'unknown_product', 'productId', p_product_id);
  END IF;
  -- Look up days from plans table
  SELECT coalesce(duration_days, 30) INTO v_days FROM plans WHERE code = v_plan_code;
  v_ends_at := p_now + (v_days || ' days')::interval;
  -- Insert entitlement
  INSERT INTO entitlements (user_id, plan_code, source, external_ref, starts_at, ends_at)
  VALUES (p_user, v_plan_code, 'store', p_transaction_id, p_now, v_ends_at)
  ON CONFLICT (source, external_ref) DO NOTHING;
  RETURN jsonb_build_object('status', 'restored', 'planCode', v_plan_code, 'endsAt', v_ends_at);
EXCEPTION WHEN OTHERS THEN
  RETURN jsonb_build_object('status', 'error', 'detail', SQLERRM);
END $$;
