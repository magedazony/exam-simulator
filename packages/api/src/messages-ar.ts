/** Messages with a changing part. */
const AR_PATTERNS: Array<[RegExp, (m: RegExpExecArray) => string]> = [
  [/^must be one of (.+)$/, (m) => `يجب أن تكون إحدى القيم: ${m[1]}`],
  [/^must be a list drawn from (.+)$/, (m) => `يجب أن تكون قائمة من: ${m[1]}`],
  [/^must be text of (\d+) to (\d+) characters$/, (m) => `يجب أن يكون نصاً من ${m[1]} إلى ${m[2]} حرف`],
  [/^same stem as row (\d+)$/, (m) => `نص السؤال نفسه موجود في الصف ${m[1]}`],
  [/^select at most (\d+)$/, (m) => `اختر ${m[1]} على الأكثر`],
  [/^the file is (.+)$/, (m) => `نوع الملف ${m[1]}`],
  [/^The sheet has more than (\d+) rows$/, (m) => `الورقة تحتوي على أكثر من ${m[1]} صف`],
  [/^must be ([A-Z][A-Z0-9-]+)$/, (m) => `يجب أن تكون ${m[1]}`],
];

/** The Arabic for an English message, or the English when none is known. */
export function toArabic(text: string): string {
  if (Object.hasOwn(AR_MESSAGES, text)) return AR_MESSAGES[text]!;
  for (const [re, fn] of AR_PATTERNS) {
    const m = re.exec(text);
    if (m) return fn(m);
  }
  return text;
}

/** True when a translation exists (used by the test). */
export const hasArabic = (text: string): boolean => toArabic(text) !== text || Object.hasOwn(AR_MESSAGES, text);
